"""Linux setup helper: generate the systemd user unit that runs the remapper.

The template unit ``inpmap@.service`` runs ``inpmap run NAME`` in the
foreground under the user's systemd instance (``systemctl --user``), so a
profile starts at login, has the same device access as the logged-in user
(udev ``uaccess`` rules, see linux_setup.py) and logs to the journal
through stderr. No root, no forking.

The Python path is absolute and specific to this installation: the Python
of the virtual environment InpMap runs from (not resolved, a venv's python
is a symlink and must stay one).
"""

from __future__ import annotations

from pathlib import PurePosixPath

TEMPLATE_NAME = "inpmap@.service"  # instance NAME runs the profile NAME
UNIT_DIR = "~/.config/systemd/user"

# Exit codes of `inpmap run` after which a restart cannot help (invalid
# configuration, wrong usage); see cli.EXIT_*. Device errors (3) are retried:
# right after login the session's device permissions may not be applied yet.
NO_RESTART_EXIT_CODES = (1, 2)


class UnitError(ValueError):
    """A path cannot be written into a unit file."""


def quote(word: str, *, command: bool = False) -> str:
    """Quote one ExecStart word for systemd, with specifiers (``%``) escaped.

    Checked with ``systemd-analyze verify``: spaces and ``%%`` work in the
    command path and in arguments; ``\\"`` works in arguments, but systemd
    rejects quotes and backslashes in the command path. ``$`` is rejected
    everywhere: systemd expands variables in arguments but not in the command
    path, so no single escaping is right for both.
    """
    forbidden = ["\n", "\r", "$"] + (['"', "\\"] if command else [])
    bad = sorted({char for char in forbidden if char in word})
    if bad:
        shown = ", ".join(repr(char) for char in bad)
        raise UnitError(f"path contains {shown}, which the unit file cannot express: {word}")
    escaped = word.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%")
    return f'"{escaped}"'


def render_unit(python: str, config_dir: str, profiles: list[tuple[str, str]]) -> str:
    """The template unit ``inpmap@.service``: instance NAME runs profile NAME.

    ``profiles`` lists (name, state) of the profiles found, for the comments.
    The profile is looked up by `inpmap run` itself (``config_dir``/NAME.inpmap).
    """
    if not PurePosixPath(python).is_absolute():
        raise UnitError(f"path must be absolute: {python}")
    example = profiles[0][0] if profiles else "default"
    unit = f"inpmap@{example}.service"
    header = [
        "# InpMap user service, generated by `inpmap service-unit`.",
        f"# Instance NAME runs the profile {config_dir}/NAME.inpmap while you are",
        "# logged in, as your user (no root). Run one profile at a time.",
        "#",
        "# Profiles found when this file was generated (more can be added at any time):",
        *([f"#   {name:<20} {state}" for name, state in profiles] or ["#   (none yet)"]),
        "#",
        f"# Install: mkdir -p {UNIT_DIR}",
        f"#          inpmap service-unit > {UNIT_DIR}/{TEMPLATE_NAME}",
        "#          systemctl --user daemon-reload",
        f"# Use:     systemctl --user enable --now {unit}   (starts it at every login)",
        f"# Switch:  systemctl --user stop 'inpmap@*' && systemctl --user start {unit}",
        f"# Logs:    journalctl --user -u {unit}",
        "# Enabled: systemctl --user list-unit-files 'inpmap@*'",
        "# Remove:  systemctl --user stop 'inpmap@*'",
        "#          systemctl --user disable inpmap@NAME.service   (each enabled profile)",
        f"#          rm {UNIT_DIR}/{TEMPLATE_NAME}",
        "#          systemctl --user daemon-reload",
        "#",
        "# Regenerate this file if InpMap moves (e.g. a new virtual environment).",
    ]
    exec_start = " ".join(
        [quote(python, command=True), "-m", "inpmap", "run", "--wait-for-devices", "%i"]
    )
    lines = [
        *header,
        "",
        "[Unit]",
        "Description=InpMap input remapper, profile %i",
        # Give up after repeated failures instead of restarting forever.
        "StartLimitIntervalSec=60",
        "StartLimitBurst=5",
        "",
        "[Service]",
        "Type=exec",
        f"ExecStart={exec_start}",
        "Restart=on-failure",
        "RestartSec=3",
        "RestartPreventExitStatus=" + " ".join(str(c) for c in NO_RESTART_EXIT_CODES),
        "Environment=PYTHONUNBUFFERED=1",
        "NoNewPrivileges=yes",
        "",
        "[Install]",
        "WantedBy=default.target",
    ]
    return "\n".join(lines) + "\n"
