"""Linux setup helper: generate a systemd user unit that runs the remapper.

The unit runs ``inpmap run`` in the foreground under the user's systemd
instance (``systemctl --user``), so it starts at login, has the same device
access as the logged-in user (udev ``uaccess`` rules, see linux_setup.py)
and logs to the journal through stderr. No root, no forking.

Paths are absolute and specific to this installation: the Python of the
virtual environment InpMap runs from (not resolved, a venv's python is a
symlink and must stay one) and the configuration file.
"""

from __future__ import annotations

from pathlib import PurePosixPath

UNIT_NAME = "inpmap.service"
UNIT_DIR = "~/.config/systemd/user"

# Exit codes of `inpmap run` after which a restart cannot help (invalid
# configuration, wrong usage); see cli.EXIT_*. Device errors (3) are retried:
# right after login the session's device permissions may not be applied yet.
NO_RESTART_EXIT_CODES = (1, 2)


class UnitError(ValueError):
    """A path cannot be written into a unit file."""


def quote(word: str, *, command: bool = False) -> str:
    """Quote one ExecStart word for systemd, with specifiers (``%``) escaped.

    Checked with ``systemd-analyze verify``: spaces and ``%%`` work in the
    command path and in arguments; ``\\"`` works in arguments, but systemd
    rejects quotes and backslashes in the command path. ``$`` is rejected
    everywhere: systemd expands variables in arguments but not in the command
    path, so no single escaping is right for both.
    """
    forbidden = ["\n", "\r", "$"] + (['"', "\\"] if command else [])
    bad = sorted({char for char in forbidden if char in word})
    if bad:
        shown = ", ".join(repr(char) for char in bad)
        raise UnitError(f"path contains {shown}, which the unit file cannot express: {word}")
    escaped = word.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%")
    return f'"{escaped}"'


def render_unit(python: str, config_path: str, source: str) -> str:
    """The unit file text for running ``config_path`` with ``python -m inpmap``."""
    for path in (python, config_path):
        if not PurePosixPath(path).is_absolute():
            raise UnitError(f"path must be absolute: {path}")
    exec_start = " ".join(
        [
            quote(python, command=True),
            "-m",
            "inpmap",
            "run",
            "--wait-for-devices",
            quote(config_path),
        ]
    )
    description = config_path.replace("%", "%%")
    lines = [
        f"# InpMap user service, generated by `inpmap service-unit {source}`.",
        "# Runs the remapper while you are logged in, as your user (no root).",
        "#",
        f"# Install: mkdir -p {UNIT_DIR}",
        f"#          inpmap service-unit {source} > {UNIT_DIR}/{UNIT_NAME}",
        "#          systemctl --user daemon-reload",
        f"#          systemctl --user enable --now {UNIT_NAME}",
        f"# Logs:    journalctl --user -u {UNIT_NAME}",
        "# After editing the configuration: systemctl --user restart inpmap",
        f"# Remove:  systemctl --user disable --now {UNIT_NAME}",
        f"#          rm {UNIT_DIR}/{UNIT_NAME}",
        "#          systemctl --user daemon-reload",
        "#",
        "# Regenerate this file if InpMap or the configuration file moves.",
        "",
        "[Unit]",
        f"Description=InpMap input remapper ({description})",
        # Give up after repeated failures instead of restarting forever.
        "StartLimitIntervalSec=60",
        "StartLimitBurst=5",
        "",
        "[Service]",
        "Type=exec",
        f"ExecStart={exec_start}",
        "Restart=on-failure",
        "RestartSec=3",
        "RestartPreventExitStatus=" + " ".join(str(c) for c in NO_RESTART_EXIT_CODES),
        "Environment=PYTHONUNBUFFERED=1",
        "NoNewPrivileges=yes",
        "",
        "[Install]",
        "WantedBy=default.target",
    ]
    return "\n".join(lines) + "\n"
