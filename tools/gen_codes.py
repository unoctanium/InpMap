"""Generate src/inpmap/_linux_codes.py from the kernel's input-event-codes.h.

Linux event code names (KEY_X, BTN_SOUTH, ...) are the project's canonical
vocabulary for keys and buttons. The table is checked in so that the core
(config validation, mapping engine) needs neither evdev nor kernel headers at
runtime, and stays usable by a future non-Linux backend.

Usage:
    python tools/gen_codes.py [/usr/include/linux/input-event-codes.h]
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

DEFAULT_HEADER = Path("/usr/include/linux/input-event-codes.h")
OUTPUT = Path(__file__).resolve().parent.parent / "src" / "inpmap" / "_linux_codes.py"

# Range markers and sentinels share values with real codes. Excluding them keeps
# canonical names meaningful (0x130 -> BTN_SOUTH, not BTN_GAMEPAD).
EXCLUDED = {
    "KEY_RESERVED",
    "KEY_MIN_INTERESTING",
    "KEY_MAX",
    "KEY_CNT",
    "BTN_MISC",
    "BTN_MOUSE",
    "BTN_JOYSTICK",
    "BTN_GAMEPAD",
    "BTN_DIGI",
    "BTN_WHEEL",
    "BTN_TRIGGER_HAPPY",
}

DEFINE = re.compile(r"^#define\s+((?:KEY|BTN)_\w+)\s+(\w+)")


def parse(header: str) -> tuple[dict[str, int], dict[int, str]]:
    """Return (name -> code, code -> canonical name).

    The canonical name of a code is the first name defined with a numeric
    literal; names defined as another name are aliases.
    """
    codes: dict[str, int] = {}
    canonical: dict[int, str] = {}
    for line in header.splitlines():
        match = DEFINE.match(line)
        if not match:
            continue
        name, value = match.groups()
        if name in EXCLUDED:
            continue
        if value in codes:
            codes[name] = codes[value]
            continue
        try:
            code = int(value, 0)
        except ValueError:
            # Alias of an excluded marker (e.g. BTN_TRIGGER_HAPPY1 is literal,
            # but guard against future header changes).
            raise SystemExit(f"cannot resolve {name} = {value}") from None
        codes[name] = code
        canonical.setdefault(code, name)
    return codes, canonical


def render(codes: dict[str, int], canonical: dict[int, str], source: Path) -> str:
    lines = [
        f'"""Linux EV_KEY code names. Generated by tools/gen_codes.py from {source}.',
        "",
        "Do not edit by hand; re-run the generator instead.",
        '"""',
        "",
        "CODES: dict[str, int] = {",
    ]
    lines += [f'    "{name}": {code:#06x},' for name, code in codes.items()]
    lines += ["}", "", "CANONICAL_NAMES: dict[int, str] = {"]
    lines += [f'    {code:#06x}: "{name}",' for code, name in sorted(canonical.items())]
    lines += ["}", ""]
    return "\n".join(lines)


def main() -> None:
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_HEADER
    codes, canonical = parse(source.read_text())
    OUTPUT.write_text(render(codes, canonical, source))
    print(f"wrote {len(codes)} names ({len(canonical)} codes) to {OUTPUT}")


if __name__ == "__main__":
    main()
